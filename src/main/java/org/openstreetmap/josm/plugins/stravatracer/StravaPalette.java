    /** Below this alpha value, a pixel is considered as empty. */
    private static final int MIN_ALPHA = 16;

    private static final Map<Integer, Integer> CACHE = new ConcurrentHashMap<>();

    private StravaPalette() {
    }

    /**
     * Returns the intensity of a pixel.
     * @param argb pixel colour
     * @param hot {@code true} for the "hot" palette, {@code false} for grey levels
     * @return intensity between 0 and 255
     */
    public static int intensity(int argb, boolean hot) {
        int alpha = argb >>> 24;
        if (alpha < MIN_ALPHA) {
            return 0;
        }
        if (hot) {
            // The alpha channel of the Strava tiles grows with the intensity, like the colour:
            // the colour alone gives the intensity
            return CACHE.computeIfAbsent(argb & 0xFFFFFF, StravaPalette::nearestHotIndex);
        }
        return luminance(argb) * alpha / 255;
    }

    private static int nearestHotIndex(int rgb) {
        int best = 0;
        int bestDistance = Integer.MAX_VALUE;
        for (int i = 0; i < HOT.length; i++) {
            int dr = ((rgb >> 16) & 0xFF) - ((HOT[i] >> 16) & 0xFF);
            int dg = ((rgb >> 8) & 0xFF) - ((HOT[i] >> 8) & 0xFF);
            int db = (rgb & 0xFF) - (HOT[i] & 0xFF);
            int d = dr * dr + dg * dg + db * db;
            if (d < bestDistance) {
                bestDistance = d;
                best = i;
            }
        }
        return best;
    }

    private static int luminance(int argb) {
        return (((argb >> 16) & 0xFF) * 299 + ((argb >> 8) & 0xFF) * 587 + (argb & 0xFF) * 114) / 1000;
    }

    /**
     * Returns the colour of the "hot" palette for an intensity (used by the tests).
     * @param intensity intensity between 0 and 255
     * @return RGB colour
     */
    static int hotColour(int intensity) {
        return HOT[intensity];
    }
